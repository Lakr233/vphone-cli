import Darwin
import Foundation

/// A bad tool argument. It becomes a -32602 reply, and no socket request is sent.
struct ArgumentError: Error {
    let message: String
}

/// A failure before the server runs. `main` prints it with the usage line and exits 2.
struct StartupError: Error {
    let problem: String
}

let catalogProblem = "guest catalog does not parse; rebuild vphone-mcp from a GuestCatalog.swift generated by run-methods-tests.sh --write-catalog"

let usageLine = "usage: vphone-mcp [--profile full|standard|readonly] [--tools a,b,c]"

/// The two stderr lines of a usage failure.
func usageText(_ problem: String) -> String {
    "vphone-mcp: \(problem)\n\(usageLine)\n"
}

/// The most bytes a request line may hold, not counting its newline.
let lineLimit = 1_048_576

/// The message of the -32700 reply to a line that is not JSON.
let parseErrorMessage = "parse error: line is not valid JSON"

/// The JSON-RPC server. Each request line gets at most one reply line. Every tool call
/// goes to the VM its required `vm` argument names.
final class MCPServer {
    let profile: Profile
    let allowed: Set<String>
    let deadlines: Deadlines
    let env: [String: String]
    /// The group tools of the embedded guest catalog under `profile`; fixed for the process lifetime.
    private let generated: [Tool]

    /// `catalogJSON` is for tests; the server otherwise uses the embedded `guestCatalogJSON`. A catalog that does not
    /// parse is a startup failure.
    init(profile: Profile = .full, allowed: Set<String> = Set(toolNames), deadlines: Deadlines = Deadlines(),
         env: [String: String] = ProcessInfo.processInfo.environment, catalogJSON: String = guestCatalogJSON) throws {
        guard let catalog = parseCatalog(catalogJSON) else { throw StartupError(problem: catalogProblem) }
        generated = groupTools(catalog, profile: profile)
        self.profile = profile
        self.allowed = allowed
        self.env = env
        self.deadlines = deadlines
    }

    /// The reply line for one request line, or nil for a notification.
    func handle(line: String) -> String? {
        guard let data = line.data(using: .utf8),
              let value = try? JSONSerialization.jsonObject(with: data, options: .fragmentsAllowed),
              !hasNonFiniteNumber(value) else {
            return errorReply(id: nil, code: -32700, message: parseErrorMessage)
        }
        guard let object = value as? [String: Any], let method = object["method"] as? String else {
            return errorReply(id: nil, code: -32600, message: "invalid request: expected an object with a string method")
        }
        guard let id = object["id"] else { return nil }
        guard isValidID(id) else {
            return errorReply(id: nil, code: -32600, message: "invalid request: id must be a string, number or null")
        }
        switch method {
        case "initialize":
            return reply(id: id, result: [
                "protocolVersion": "2025-06-18",
                "capabilities": ["tools": [String: Any]()],
                "serverInfo": ["name": "vphone-mcp", "version": "1.0.0"],
            ])
        case "ping":
            return reply(id: id, result: [String: Any]())
        case "tools/list":
            return reply(id: id, result: ["tools": toolList()])
        case "tools/call":
            return callTool(id: id, params: object["params"])
        default:
            return errorReply(id: id, code: -32601, message: "method \(method) not found")
        }
    }

    private func isValidID(_ id: Any) -> Bool {
        id is NSNull || id is String || jsonNumber(id) != nil
    }

    /// The tools this server offers now: host tools the profile allows, then the generated group tools.
    private func offered() -> [Tool] {
        (hostTools.filter { profile.allows($0.access) } + generated).filter { allowed.contains($0.name) }
    }

    private func toolList() -> [[String: Any]] {
        offered().map {
            ["name": $0.name, "description": $0.description, "inputSchema": $0.inputSchema,
             "annotations": $0.annotations] as [String: Any]
        }
    }

    /// The socket of the VM a call names.
    private func targetSocket(vm: String) throws -> MachineSocket {
        let directory = (libraryRoot(env: env) as NSString).appendingPathComponent(vm)
        var isDirectory: ObjCBool = false
        guard FileManager.default.fileExists(atPath: directory, isDirectory: &isDirectory), isDirectory.boolValue else {
            throw SocketError(message: unknownVMMessage(vm, libraryRoot(env: env)))
        }
        let path = vmSocketPath(vm, env: env)
        guard FileManager.default.fileExists(atPath: path) else { throw SocketError(message: notRunningMessage(vm)) }
        return MachineSocket(path: path, deadlines: deadlines)
    }

    private func callTool(id: Any, params: Any?) -> String {
        let fields = params as? [String: Any] ?? [:]
        guard let raw = fields["name"] else {
            return errorReply(id: id, code: -32602, message: "invalid argument name: missing")
        }
        guard let name = raw as? String else {
            return errorReply(id: id, code: -32602, message: "invalid argument name: must be a non-empty string")
        }
        var arguments: [String: Any] = [:]
        if let raw = fields["arguments"] {
            guard let object = raw as? [String: Any] else {
                return errorReply(id: id, code: -32602, message: "invalid argument arguments: must be an object")
            }
            arguments = object
        }
        guard toolNames.contains(name) else {
            return errorReply(id: id, code: -32602, message: "unknown tool \(name); call tools/list for the available names")
        }
        guard allowed.contains(name) else {
            return errorReply(id: id, code: -32602, message: "tool \(name) is not enabled; add it to --tools")
        }
        let host = hostTools.first(where: { $0.name == name })
        if let host {
            guard profile.allows(host.access) else {
                return errorReply(id: id, code: -32602, message: notInProfileMessage(name, profile.rawValue))
            }
        }
        guard let rawVM = arguments["vm"] else {
            return errorReply(id: id, code: -32602, message: "invalid argument vm: missing")
        }
        guard let vm = rawVM as? String, validVMName(vm) else {
            return errorReply(id: id, code: -32602, message: "invalid argument vm: must be a valid vm name (one directory name, no /)")
        }
        if let host {
            let known = ((host.inputSchema["properties"] as? [String: Any]) ?? [:]).keys
            if let unknown = arguments.keys.sorted().first(where: { $0 != "vm" && !known.contains($0) }) {
                return errorReply(id: id, code: -32602, message: "invalid argument \(unknown): unknown argument; \(name) takes \(known.sorted().joined(separator: ", "))")
            }
        }
        arguments["vm"] = nil
        do {
            let socket = try targetSocket(vm: vm)
            guard let tool = host ?? generated.first(where: { $0.name == name }) else {
                return errorReply(id: id, code: -32602, message: notInProfileMessage(name, profile.rawValue))
            }
            return reply(id: id, result: content(try tool.run(socket, arguments)))
        } catch let error as ArgumentError {
            return errorReply(id: id, code: -32602, message: error.message)
        } catch let error as SocketError {
            return reply(id: id, result: content(.failure(error.message)))
        } catch {
            return reply(id: id, result: content(.failure(error.localizedDescription)))
        }
    }

    private func content(_ result: ToolResult) -> [String: Any] {
        switch result {
        case .text(let text):
            return ["content": [["type": "text", "text": text] as [String: Any]]]
        case .images(let images, let caption):
            let parts = images.map { ["type": "image", "data": $0.base64, "mimeType": $0.mimeType] as [String: Any] }
            return ["content": parts + [["type": "text", "text": caption] as [String: Any]]]
        case .failure(let message):
            return ["content": [["type": "text", "text": message] as [String: Any]], "isError": true]
        }
    }

    private func reply(id: Any, result: Any) -> String {
        encode(["jsonrpc": "2.0", "id": id, "result": result])
    }
}

/// The error reply for a request, with `id` null when the request has no usable id.
func errorReply(id: Any?, code: Int, message: String) -> String {
    let idValue: Any = id ?? NSNull()
    return encode(["jsonrpc": "2.0", "id": idValue, "error": ["code": code, "message": message]])
}

private func encode(_ object: [String: Any]) -> String {
    guard let data = try? JSONSerialization.data(withJSONObject: object, options: [.sortedKeys, .withoutEscapingSlashes]) else {
        return #"{"error":{"code":-32603,"message":"internal error: reply is not JSON"},"id":null,"jsonrpc":"2.0"}"#
    }
    return String(decoding: data, as: UTF8.self)
}

/// Whether `value` holds a number that is not finite (JSON `1e400` parses to
/// infinity), at any depth. JSONSerialization raises on such a value when it is
/// encoded again, and that exception cannot be caught.
private func hasNonFiniteNumber(_ value: Any) -> Bool {
    if let array = value as? [Any] { return array.contains(where: hasNonFiniteNumber) }
    if let object = value as? [String: Any] { return object.values.contains(where: hasNonFiniteNumber) }
    return !(jsonNumber(value)?.isFinite ?? true)
}

/// The VM library: `$VPHONE_LIBRARY_ROOT`, else `~/.vphone/machines`.
func libraryRoot(env: [String: String]) -> String {
    env["VPHONE_LIBRARY_ROOT"].flatMap { $0.isEmpty ? nil : $0 } ?? NSString(string: "~/.vphone/machines").expandingTildeInPath
}

/// Whether `name` can name a VM directory.
func validVMName(_ name: String) -> Bool {
    !name.isEmpty && name != "." && name != ".." && !name.contains("/")
}

func vmSocketPath(_ name: String, env: [String: String]) -> String {
    "\(libraryRoot(env: env))/\(name)/vphone.sock"
}

/// Writes `line` and a newline to stdout, retrying until every byte is written.
/// False on an error; the errno is then the one that failed.
func writeStdout(_ line: String) -> Bool {
    let bytes = Array((line + "\n").utf8)
    var sent = 0
    while sent < bytes.count {
        let count = bytes.withUnsafeBytes { Darwin.write(STDOUT_FILENO, $0.baseAddress! + sent, $0.count - sent) }
        if count < 0 && errno == EINTR { continue }
        if count <= 0 { return false }
        sent += count
    }
    return true
}

/// Reads newline-delimited lines from `fd`. Each line goes to `handle`, and each
/// reply it gives goes to `write` without its newline. A blank line and a line
/// that is not UTF-8 are not handled: a blank line gets no reply and a bad line
/// gets -32700. A line over 1 MiB gets one -32600 reply, and its bytes are
/// dropped up to the newline, so a long line is never held whole.
/// Returns nil at end of input, otherwise the failure message.
func readLines(fd: Int32, handle: (String) -> String?, write: (String) -> Bool) -> String? {
    var line: [UInt8] = []
    var overlong = false
    var chunk = [UInt8](repeating: 0, count: 65_536)

    func finish() -> String? {
        let reply: String?
        if overlong {
            reply = errorReply(id: nil, code: -32600, message: "invalid request: line over 1048576 bytes")
        } else if let text = String(bytes: line, encoding: .utf8) {
            reply = text.allSatisfy({ $0.isWhitespace }) ? nil : handle(text)
        } else {
            reply = errorReply(id: nil, code: -32700, message: parseErrorMessage)
        }
        line.removeAll(keepingCapacity: true)
        overlong = false
        guard let reply else { return nil }
        return write(reply) ? nil : "stdout write failed: \(String(cString: strerror(errno)))"
    }

    while true {
        let count = read(fd, &chunk, chunk.count)
        if count < 0 && errno == EINTR { continue }
        if count < 0 { return "stdin read failed: \(String(cString: strerror(errno)))" }
        if count == 0 { break }
        for byte in chunk[..<count] {
            if byte == 10 {
                if let failure = finish() { return failure }
            } else if !overlong {
                if line.count == lineLimit {
                    overlong = true
                    line.removeAll()
                } else {
                    line.append(byte)
                }
            }
        }
    }
    if !line.isEmpty || overlong { return finish() }
    return nil
}
