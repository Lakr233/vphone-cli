                for (int k = 0; k < 2; k++) {
                    io_connect_t cc = 0;
                    kern_return_t o = IOServiceOpen(s, mach_task_self(), 2, &cc);
                    if (o) { size_t ln = strlen(line); snprintf(line + ln, sizeof line - ln, " open%d=0x%08x", k, o); continue; }
