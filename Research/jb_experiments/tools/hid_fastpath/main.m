// The iOS SDK ships no public IOHIDLib.h; the one HID entry point used here is declared by hand
// (same signature as macOS IOHIDLib.h / open-source IOHIDFamily IOHIDUserDeviceUserClient).
// IOHIDUserDeviceCreate is declared in macOS IOKit but is NOT exported by iOS IOKit (link fails), so the
// "create a virtual HID device from an app" path is not available through the public API.

static FILE *g_log;

static void L(const char *fmt, ...) {
    va_list ap;
    va_start(ap, fmt);
    vfprintf(g_log, fmt, ap);
    va_end(ap);
    fputc('\n', g_log);
    fflush(g_log);
}


// Enumerate every IOHIDEventService instance: class, registry name, and IOServiceOpen result for type 0/1/2.
// No selectors are called. The stock probe used IOServiceGetMatchingService, i.e. the first instance only.
static void probe_all(NSString *cls) {
    io_iterator_t it = 0;
    CFMutableDictionaryRef m = IOServiceMatching(cls.UTF8String);
    if (!m || IOServiceGetMatchingServices(kIOMainPortDefault, m, &it) != KERN_SUCCESS) { L("ENUM %s: no iterator", cls.UTF8String); return; }
    int n = 0;
    io_service_t s;
    while ((s = IOIteratorNext(it))) {
        n++;
        io_name_t nm = ""; IORegistryEntryGetName(s, nm);
        CFTypeRef cn = IORegistryEntryCreateCFProperty(s, CFSTR("IORegistryEntryName"), kCFAllocatorDefault, 0);
        CFTypeRef ucc = IORegistryEntryCreateCFProperty(s, CFSTR("IOUserClientClass"), kCFAllocatorDefault, 0);
        NSString *cns = cn ? [NSString stringWithString:(__bridge NSString *)cn] : @"-";
        NSString *uc = ucc ? [NSString stringWithString:(__bridge NSString *)ucc] : @"-";
        char line[400];
        snprintf(line, sizeof line, "INST %s #%d name=%s entryName=%s UC=%s", cls.UTF8String, n, nm, cns.UTF8String, uc.UTF8String);
        if (cn) CFRelease(cn);
        if (ucc) CFRelease(ucc);
        for (int t = 0; t < 3; t++) {
            io_connect_t c = 0;
            kern_return_t r = IOServiceOpen(s, mach_task_self(), t, &c);
            size_t ln = strlen(line);
            snprintf(line + ln, sizeof line - ln, " | t%d=0x%08x", t, r);
            if (r == KERN_SUCCESS) {
                // FastPath selector "open" (23F84 0x96c7388): structureInput = OSUnserializeBinary dictionary,
                // scalar [0] = client pid. Without com.apple.hid.system.user-access-fast-path the dictionary
                // must contain FastPathMotionEventEntitlement. Try both keys, one connection per instance.
